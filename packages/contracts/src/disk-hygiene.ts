import { z } from "zod";
import { Timestamp } from "./common";

const Bytes = z.int().nonnegative();

/** Local cleanup policy. Scheduled removals are independently gated by a preview approval. */
export const DiskHygieneConfig = z.strictObject({
  enabled: z.boolean().default(false),
  dryRun: z.boolean().default(true),
  cacheBudgetBytes: Bytes.default(5 * 1024 ** 3),
  protectPaths: z.array(z.string().min(1).max(4096)).max(100).default([]),
});
export type DiskHygieneConfig = z.infer<typeof DiskHygieneConfig>;

export const DiskHygieneItem = z.object({
  path: z.string(),
  disposition: z.enum(["removed", "preview", "protected", "listed"]),
  bytes: Bytes,
  reason: z.string(),
});
export type DiskHygieneItem = z.infer<typeof DiskHygieneItem>;

/** Null project ID identifies machine-wide items, which are counted only once. */
export const DiskHygieneReport = z.object({
  id: z.string(),
  version: z.string(),
  at: Timestamp,
  trigger: z.enum(["manual", "nightly", "update"]),
  dryRun: z.boolean(),
  scopes: z.array(
    z.object({
      projectId: z.string().nullable(),
      name: z.string(),
      bytesFreed: Bytes,
      items: z.array(DiskHygieneItem),
    }),
  ),
});
export type DiskHygieneReport = z.infer<typeof DiskHygieneReport>;

export const DiskHygieneStatus = z.object({
  config: DiskHygieneConfig,
  version: z.string(),
  previewId: z.string().nullable(),
  approved: z.boolean(),
  report: DiskHygieneReport.nullable(),
  history: z.array(DiskHygieneReport).max(14).default([]),
});
export type DiskHygieneStatus = z.infer<typeof DiskHygieneStatus>;

/** Approval can only name a preview already generated by this version. */
export const DiskHygieneCommand = z.discriminatedUnion("action", [
  z.strictObject({ action: z.literal("configure"), config: DiskHygieneConfig }),
  z.strictObject({ action: z.literal("preview") }),
  z.strictObject({ action: z.literal("approve"), previewId: z.string().min(1) }),
  z.strictObject({ action: z.literal("run") }),
]);
export type DiskHygieneCommand = z.infer<typeof DiskHygieneCommand>;
